function renderIcon(name, options = {}) {
  const size = options.size ?? 18;
  const stroke = options.strokeWidth ?? 1.75;
  const className = options.className ? ` class="${options.className}"` : "";
  const inner = ICON_PATHS[name];
  if (!inner) return "";
  return (
    `<svg xmlns="http://www.w3.org/2000/svg" width="${size}" height="${size}" ` +
    `viewBox="0 0 24 24" fill="none" stroke="currentColor" ` +
    `stroke-width="${stroke}" stroke-linecap="round" stroke-linejoin="round" ` +
    `aria-hidden="true"${className}>${inner}</svg>`
  );
}

function applyIcons(root = document) {
  root.querySelectorAll("[data-icon]").forEach((el) => {
    if (el.dataset.iconApplied === "true") return;
    const name = el.dataset.icon;
    const size = el.dataset.iconSize ? Number(el.dataset.iconSize) : undefined;
    const stroke = el.dataset.iconStroke ? Number(el.dataset.iconStroke) : undefined;
    el.innerHTML = renderIcon(name, { size, strokeWidth: stroke });
    el.dataset.iconApplied = "true";
  });
}

window.MarshalIcons = { render: renderIcon, apply: applyIcons, paths: ICON_PATHS };
